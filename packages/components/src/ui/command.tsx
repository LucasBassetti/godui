function CommandList({
  className,
  children,
  ref,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.List>) {
  const listRef = React.useRef<HTMLDivElement>(null);
  const indicatorRef = React.useRef<HTMLSpanElement>(null);
  const setListRef = React.useCallback(
    (node: HTMLDivElement | null) => {
      listRef.current = node;
      if (typeof ref === "function") ref(node);
      else if (ref) ref.current = node;
    },
    [ref],
  );
  // One highlight follows the selected item. cmdk moves `data-selected` on
  // arrow keys and pointer moves (slide); filtering re-renders items (snap).
  useActiveIndicator(listRef, indicatorRef, {
    active: '[cmdk-item][data-selected="true"]',
    items: "[cmdk-item]",
    attributes: ["data-selected"],
  });

  return (
    <CommandPrimitive.List
      ref={setListRef}
      data-slot="command-list"
      className={cn(
        "relative max-h-[300px] scroll-py-1 overflow-x-hidden overflow-y-auto",
        className,
      )}
      {...props}
    >
      {/* Hidden until measured, so the first paint keeps shadcn's styling.
          Skipped with asChild: the Slot needs a single child. */}
      {props.asChild ? (
        children
      ) : (
        <>
          <span
            ref={indicatorRef}
            data-slot="command-indicator"
            aria-hidden="true"
            className="pointer-events-none absolute top-0 left-0 hidden origin-top-left rounded-sm bg-accent ease-spring-snappy in-[[data-slot=command-list][data-indicator=ready]]:block"
          />
          {children}
        </>
      )}
    </CommandPrimitive.List>
  );
}

